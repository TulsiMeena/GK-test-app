    /**
     * All Questions in the Competitive GK Database
     */
    val allQuestions: List<GkQuestion>
        get() {
            if (_allQuestions.isEmpty()) {
                populateQuestions(builtInQuestions)
            }
            return _allQuestions
        }

    /**
     * Total number of questions loaded
     */
    val totalCount: Int
        get() = allQuestions.size

    private fun populateQuestions(list: List<GkQuestion>) {
        for (q in list) {
            if (!questionsById.containsKey(q.id)) {
                _allQuestions.add(q)
                questionsById[q.id] = q

                val normCatId = q.categoryId.lowercase()
                val rawCatId = normCatId.removePrefix("cat_")
                val catTitle = q.category.lowercase()

                questionsByCategory.getOrPut(normCatId) { mutableListOf() }.add(q)
                questionsByCategory.getOrPut("cat_$rawCatId") { mutableListOf() }.add(q)
                questionsByCategory.getOrPut(rawCatId) { mutableListOf() }.add(q)
                questionsByCategory.getOrPut(catTitle) { mutableListOf() }.add(q)
            }
        }
    }

    /**
     * Loads all questions from assets at startup and merges with built-in questions.
     */
    fun initialize(context: Context) {
        if (isInitialized) return
        synchronized(this) {
            if (isInitialized) return
            try {
                // Ensure built-ins are populated
                populateQuestions(builtInQuestions)

                val loadedList = loadAllQuestionsFromAssets(context)
                if (loadedList.isNotEmpty()) {
                    populateQuestions(loadedList)
                }
                isInitialized = true
            } catch (e: Exception) {
                e.printStackTrace()
            }
        }
    }

    private fun loadAllQuestionsFromAssets(context: Context): List<GkQuestion> {
        val result = mutableListOf<GkQuestion>()
        try {
            val assetList = context.assets.list("questions") ?: emptyArray()
            for (fileName in assetList) {
                if (fileName.endsWith(".json")) {
                    try {
                        val jsonString = context.assets.open("questions/$fileName").bufferedReader().use { it.readText() }
                        val jsonArray = JSONArray(jsonString)
                        for (i in 0 until jsonArray.length()) {
                            val obj = jsonArray.getJSONObject(i)

                            val optHiJson = obj.getJSONArray("optionsHindi")
                            val optEnJson = obj.optJSONArray("optionsEnglish") ?: optHiJson

                            val optHi = mutableListOf<String>()
                            val optEn = mutableListOf<String>()
                            for (j in 0 until optHiJson.length()) {
                                optHi.add(optHiJson.getString(j))
                            }
                            for (j in 0 until optEnJson.length()) {
                                optEn.add(optEnJson.getString(j))
                            }

                            val q = GkQuestion(
                                id = obj.getString("id"),
                                category = obj.getString("category"),
                                categoryId = obj.getString("categoryId"),
                                subtopic = obj.getString("subtopic"),
                                questionHindi = obj.getString("questionHindi"),
                                questionEnglish = obj.optString("questionEnglish", obj.getString("questionHindi")),
                                optionsHindi = optHi,
                                optionsEnglish = optEn,
                                correctAnswerIndex = obj.getInt("correctAnswerIndex"),
                                explanationHindi = obj.getString("explanationHindi"),
                                explanationEnglish = obj.optString("explanationEnglish", obj.getString("explanationHindi")),
                                difficulty = obj.optString("difficulty", "Moderate")
                            )
                            result.add(q)
                        }
                    } catch (e: Exception) {
                        e.printStackTrace()
                    }
                }
            }
        } catch (e: Exception) {
            e.printStackTrace()
        }
        return result
    }

