    fun getQuestionsByTopic(topicId: String, subtopic: String = ""): List<GkQuestion> {
        return _allQuestions.filter {
            it.subtopic.contains(topicId, ignoreCase = true) ||
            (subtopic.isNotBlank() && it.subtopic.contains(subtopic, ignoreCase = true))
        }
    }

    /**
     * Strictly isolated query for a specific Category and Topic.
     * Never returns questions from other categories or topics.
     */
    fun getQuestionsForTopic(
        categoryId: String,
        topicId: String,
        topicTitle: String = ""
    ): List<GkQuestion> {
        val topicNormalized = topicId.lowercase()
        // Direct match by subtopic code or ID prefix (e.g. hist_1, pol_1)
        val directMatches = _allQuestions.filter {
            it.subtopic.equals(topicId, ignoreCase = true) ||
            it.subtopic.equals(topicNormalized, ignoreCase = true) ||
            it.id.startsWith("${topicNormalized}_", ignoreCase = true)
        }
        if (directMatches.isNotEmpty()) return directMatches

        val catQuestions = getQuestionsByCategory(categoryId)
        if (catQuestions.isEmpty()) return emptyList()

        return catQuestions.filter { q ->
            q.subtopic.contains(topicId, ignoreCase = true) ||
            (topicTitle.isNotBlank() && q.subtopic.contains(topicTitle, ignoreCase = true)) ||
            (topicTitle.isNotBlank() && q.category.contains(topicTitle, ignoreCase = true))
        }
    }

    /**
     * Returns true dynamic available question count for a topic (no fake count)
     */
    fun getAvailableCount(
        categoryId: String,
        topicId: String,
        topicTitle: String = ""
    ): Int {
        return getQuestionsForTopic(categoryId, topicId, topicTitle).size
    }

    /**
     * Returns true dynamic available question count for a category
     */
    fun getAvailableCountForCategory(categoryId: String): Int {
        return getQuestionsByCategory(categoryId).size
    }

    fun getMockTestQuestions(categoryId: String, topicId: String, mockNumber: Int = 1): List<GkQuestion> {
        val topicQs = getQuestionsForTopic(categoryId, topicId)
        if (topicQs.isEmpty()) return emptyList()

        val prefix = "${topicId.lowercase()}_m${mockNumber}_"
        val exactMatch = topicQs.filter {
            it.id.startsWith(prefix, ignoreCase = true) ||
            it.id.contains("_m${mockNumber}_", ignoreCase = true)
        }
        if (exactMatch.size >= 15) return exactMatch.take(15)
        if (exactMatch.isNotEmpty()) {
            val remaining = topicQs.filterNot { exactMatch.contains(it) }
            return (exactMatch + remaining).take(15)
        }

        // Slicing: 15 questions per mock test without overlap
        val offset = (mockNumber - 1) * 15
        val paged = topicQs.drop(offset).take(15)
        if (paged.size >= 15) return paged
        return if (paged.isNotEmpty()) (paged + topicQs.filterNot { paged.contains(it) }).take(15) else topicQs.take(15)
    }

    /**
     * Smart question selector that filters questions based on QuizConfig
     * and produces the required question count (10, 15, 25, 50, 100).
     * Strictly maintains Category and Topic isolation when configured.
     */
    fun selectQuestionsForQuiz(config: QuizConfig): List<GkQuestion> {
        // Direct handling if a specific Mock test is requested (Mock 1 to 10)
        if (config.questionSource == QuestionSource.TOPIC && !config.targetTopicId.isNullOrBlank()) {
            val topicId = config.targetTopicId
            val catId = config.selectedCategoryIds.firstOrNull() ?: "history"
            val title = "${config.testTitle} ${config.targetTopicHindi ?: ""}"
            val regex = Regex("""(?:Mock|मॉक)\s*(?:Test\s*)?(\d+)""", RegexOption.IGNORE_CASE)
            val match = regex.find(title)
            if (match != null) {
                val mockNum = match.groupValues[1].toIntOrNull() ?: 1
                val mockQs = getMockTestQuestions(catId, topicId, mockNum)
                if (mockQs.isNotEmpty()) return mockQs
            }
        }

        // Step 1: Filter by category / topic isolation
        val categoryFiltered = when (config.questionSource) {
            QuestionSource.TOPIC -> {
                val catId = config.selectedCategoryIds.firstOrNull() ?: ""
                val topicId = config.targetTopicId ?: ""
                val topicTitle = config.targetTopicTitle ?: ""
                getQuestionsForTopic(catId, topicId, topicTitle)
            }
            QuestionSource.SINGLE_CATEGORY -> {
                val catId = config.selectedCategoryIds.firstOrNull()
                if (catId != null) {
                    getQuestionsByCategory(catId)
                } else {
                    emptyList()
                }
            }
            QuestionSource.MULTIPLE_CATEGORIES -> {
                if (config.selectedCategoryIds.isNotEmpty()) {
                    config.selectedCategoryIds.flatMap { getQuestionsByCategory(it) }
                } else {
                    emptyList()
                }
            }
            QuestionSource.RANDOM_GK -> allQuestions
        }

        if (categoryFiltered.isEmpty()) {
            return emptyList()
        }

        // Step 2: Filter by difficulty if specified
        val difficultyFiltered = if (config.difficulty == "Mixed" || config.difficulty.isBlank()) {
            categoryFiltered
        } else {
            val matching = categoryFiltered.filter { it.difficulty.equals(config.difficulty, ignoreCase = true) }
            if (matching.isNotEmpty()) matching else categoryFiltered
        }

        // Step 3: Fill to requested count without duplication
        val targetCount = config.questionCount
        val uniqueQuestions = difficultyFiltered.distinctBy { it.id }
        val shuffledPool = uniqueQuestions.shuffled(Random(System.currentTimeMillis()))

        return if (shuffledPool.size >= targetCount) {
            shuffledPool.take(targetCount)
        } else {
            shuffledPool
        }
    }

    fun getQuestionById(id: String): GkQuestion? {
        val cleanId = id.substringBefore("_V")
        return questionsById[cleanId] ?: _allQuestions.find { it.id == cleanId }
    }

    fun getQuestionsByIds(ids: Collection<String>): List<GkQuestion> {
        val cleanIds = ids.map { it.substringBefore("_V") }.toSet()
        return cleanIds.mapNotNull { getQuestionById(it) }
    }

    fun getQuestionsByCategory(categoryId: String): List<GkQuestion> {
        val normalized = categoryId.lowercase()
        val raw = normalized.removePrefix("cat_")
        val list = questionsByCategory[normalized] ?: questionsByCategory[raw] ?: questionsByCategory["cat_$raw"]
        if (!list.isNullOrEmpty()) return list
        return _allQuestions.filter {
            it.categoryId.equals(categoryId, ignoreCase = true) ||
            it.categoryId.equals(raw, ignoreCase = true) ||
            it.category.equals(categoryId, ignoreCase = true) ||
            it.category.contains(raw, ignoreCase = true)
        }
    }

    fun getQuestionsByFilter(
        categoryId: String? = null,
        difficulty: String? = null,
        count: Int = 20
    ): List<GkQuestion> {
        var pool = if (!categoryId.isNullOrBlank() && categoryId != "All") {
            getQuestionsByCategory(categoryId)
        } else {
            allQuestions
        }
        if (!difficulty.isNullOrBlank() && difficulty != "All" && difficulty != "Mixed") {
            val diffMatched = pool.filter { it.difficulty.equals(difficulty, ignoreCase = true) }
            if (diffMatched.isNotEmpty()) pool = diffMatched
        }
        return pool.shuffled(Random(System.currentTimeMillis())).take(count).ifEmpty { allQuestions.take(count) }
    }
